#!/usr/bin/env bash
# Called after the internal profile has closed paid/export switches.
set -euo pipefail
output="${1:?output path required}"
{
  printf 'export NODE_BINARY=%q\n' "$(command -v node)"
  for key in LAMPY_BUILD_PROFILE LAMPY_BUILD_NUMBER EXPO_NO_DOTENV EXPO_PUBLIC_FAMILY_INTERNAL_TEST EXPO_PUBLIC_FAMILY_ALBUM_EVAL EXPO_PUBLIC_FAMILY_ENTRY_OPEN EXPO_PUBLIC_CONTROLLED_EMAIL_ACCOUNTS EXPO_PUBLIC_FAMILY_API_BASE_URL EXPO_PUBLIC_ACCOUNT_DIAGNOSTICS EXPO_PUBLIC_FAMILY_TEST_DRIVER EXPO_PUBLIC_FAMILY_TEST_INVITE_CODE EXPO_PUBLIC_UNIFIED_PURCHASES EXPO_PUBLIC_FAMILY_ALBUM_EXPORT_ENABLED EXPO_PUBLIC_ALBUM_EXPORT_ENABLED EXPO_PUBLIC_ALBUM_PAID_EXPORT_ENABLED EXPO_PUBLIC_ALBUM_PRINT_EVAL EXPO_PUBLIC_ALBUM_EXPORT_PRODUCT_ID; do
    printf 'export %s=%q\n' "$key" "${!key}"
  done
} > "$output"
